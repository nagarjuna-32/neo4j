"""
CodeBrain AI — Phase 4 Evidence-Grounded AI Debugging Tests
Verifies:
1. Mocked LLM receives graph-retrieved evidence (decisions, bugs, fixes, tests, traversal paths).
2. Distinction between verified historical facts and inferred hypotheses.
3. Transparent fallback to deterministic engine when LLM call fails.
4. Handling of insufficient evidence explaining missing logs and diffs.
"""
import json
import pytest
from unittest.mock import MagicMock, patch
from fastapi.testclient import TestClient
from backend.app.main import app
from backend.app.services.ai_service import ai_service


@pytest.fixture
def client():
    return TestClient(app)


def test_mocked_llm_receives_graph_evidence(client):
    """
    Verify that the OpenAI API call actually receives the retrieved Neo4j evidence package:
    decisions, bugs, tests, and graph traversal paths.
    """
    mock_response = MagicMock()
    mock_choice = MagicMock()
    mock_choice.message.content = json.dumps({
        "assessment": "Grounded assessment generated by mocked LLM",
        "answer": "### Mocked Explanation\nBased on DEC-101 and BUG-101...",
        "potential_root_causes": ["Missing refresh token middleware in route pipeline"],
        "suggested_checks": ["Check TokenValidationMiddleware registration in app.main"],
        "suggested_tests": ["Execute TEST-101"],
        "evidence_limitations": "Live server logs are required to verify token header expiry.",
        "confidence_explanation": "High confidence due to direct path connection in Neo4j.",
    })
    mock_response.choices = [mock_choice]

    with patch.object(ai_service, "client") as mock_client, \
         patch.object(ai_service, "_call_openai_llm") as mock_call:
        
        # Configure return value of the call
        from backend.app.models import AnalyzeResponse, EvidenceRecord
        mock_call.return_value = AnalyzeResponse(
            question="The Users API returns HTTP 401 after the authentication refactor.",
            answer="### Mocked LLM Output\nBased on DEC-101 and BUG-101 evidence...",
            assessment="Grounded LLM Assessment",
            relevant_evidence=[
                EvidenceRecord(id="BUG-101", type="Bug", title="Users API returns HTTP 401", details={}, relation="HAS_BUG")
            ],
            evidence_paths=["(COMP-AUTH)-[:HAS_BUG]->(BUG-101)"],
            connected_decisions=["DEC-101: Migrate session authentication to JWT"],
            historical_bugs=["BUG-101: Users API returns HTTP 401 after authentication refactor"],
            potential_root_causes=["Missing refresh-token middleware"],
            suggested_checks=["Check middleware registration"],
            suggested_tests=["TEST-101"],
            evidence_limitations="Requires live request logs",
            confidence_explanation="High confidence from graph paths",
            source="openai:gpt-4.1-mini",
            project_id="PRJ-SENTINEL",
            detected_component="Authentication",
        )

        with patch.object(ai_service, "client", mock_client), \
             patch("backend.app.config.settings.OPENAI_API_KEY", "sk-mock-valid-api-key"):

            payload = {
                "project_id": "PRJ-SENTINEL",
                "question": "The Users API returns HTTP 401 after the authentication refactor. Why might this happen, and what should I investigate before merging?",
                "component": "Authentication",
            }
            res = client.post("/api/analyze", json=payload)
            assert res.status_code == 200
            data = res.json()

            # Verify that _call_openai_llm was invoked with graph context
            assert mock_call.called
            call_kwargs = mock_call.call_args[1]

            # Inspect context passed to the LLM caller
            ctx = call_kwargs["context"]
            assert any(b["id"] == "BUG-101" for b in ctx.get("bugs", []))
            assert any(d["id"] == "DEC-101" for d in ctx.get("decisions", []))
            assert any("BUG-101" in p for p in ctx.get("evidence_paths", []))
            assert data["source"].startswith("openai:")


def test_ai_debugging_insufficient_evidence_explains_missing_context(client):
    """
    When the component has no recorded history in the graph, the assistant
    must explicitly identify missing logs and code diffs without fabricating bugs.
    """
    payload = {
        "project_id": "PRJ-SENTINEL",
        "question": "Why is the Metrics Ingestion worker dropping UDP packets?",
        "component": "Metrics Ingestion Daemon",
    }
    res = client.post("/api/analyze", json=payload)
    assert res.status_code == 200
    data = res.json()

    assert "Insufficient" in data["assessment"] or "No historical" in data["assessment"]
    assert "missing" in data["evidence_limitations"].lower()
    # Must specify required diagnostic artifacts
    assert "logs" in data["evidence_limitations"].lower() or "diffs" in data["evidence_limitations"].lower()
    # Must not invent fake bugs
    assert len(data["historical_bugs"]) == 0


def test_ai_debugging_fallback_when_llm_fails(client):
    """
    Verify transparent fallback to the deterministic graph engine when OpenAI client fails.
    """
    with patch.object(ai_service, "client") as mock_client, \
         patch("backend.app.config.settings.OPENAI_API_KEY", "sk-mock-valid-key"):
        mock_client.chat.completions.create.side_effect = RuntimeError("503 Service Unavailable: OpenAI API outage")

        payload = {
            "project_id": "PRJ-SENTINEL",
            "question": "The Users API returns HTTP 401 after the authentication refactor.",
            "component": "Authentication",
        }
        res = client.post("/api/analyze", json=payload)
        assert res.status_code == 200
        data = res.json()

        # Transparent fallback disclosure
        assert "deterministic_graph_engine" in data["source"]
        assert "BUG-101" in str(data["relevant_evidence"])
        assert "DEC-101" in str(data["relevant_evidence"])
        assert len(data["suggested_checks"]) >= 3
        assert len(data["suggested_tests"]) >= 1


def test_ai_debugging_distinguishes_facts_from_hypotheses(client):
    """
    Verify that historical incidents and reasons are labeled as facts,
    while potential root causes are labeled as hypotheses.
    """
    payload = {
        "project_id": "PRJ-SENTINEL",
        "question": "The Users API returns HTTP 401 after the authentication refactor.",
        "component": "Authentication",
    }
    res = client.post("/api/analyze", json=payload)
    assert res.status_code == 200
    data = res.json()

    answer = data["answer"]
    # Check that answer contains fact vs hypothesis distinction
    assert "fact" in answer.lower()
    assert "hypothes" in answer.lower()
